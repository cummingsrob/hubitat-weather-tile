#!/usr/bin/env python3
"""Generate the Meteocons icon-pack libraries from the @meteocons/svg (animated) and
@meteocons/svg-static npm packages (basmilius/weather-icons, MIT).
  npm pack @meteocons/svg @meteocons/svg-static ; extract ; python3 tools/gen_meteocons.py <svgdir> <staticdir>
Each icon: ids prefixed per pack+key (no collisions when several icons share one tile SVG),
wrapped in a nested 60x60 <svg>, split into <=400-char string chunks, one method per icon."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = {  # our condition key -> Meteocons fill icon
    "sunny": "clear-day", "clear": "clear-day", "mostlysunny": "mostly-clear-day",
    "partlycloudy": "partly-cloudy-day", "partlysunny": "partly-cloudy-day", "mostlycloudy": "overcast-day",
    "cloudy": "cloudy", "fog": "fog", "hazy": "haze", "drizzle": "drizzle",
    "chancerain": "partly-cloudy-day-rain", "showers": "partly-cloudy-day-drizzle", "rain": "rain",
    "chancetstorms": "thunderstorms-day", "tstorms": "thunderstorms-rain",
    "chanceflurries": "partly-cloudy-day-snow", "flurries": "snow", "chancesnow": "partly-cloudy-day-snow",
    "snow": "snow", "chancesleet": "partly-cloudy-day-sleet", "sleet": "sleet", "hail": "hail", "wind": "wind",
    # night variants (today's slot only, before sunrise / after sunset); keys without one fall back to the day icon
    "nt_sunny": "clear-night", "nt_clear": "clear-night", "nt_mostlysunny": "mostly-clear-night",
    "nt_partlycloudy": "partly-cloudy-night", "nt_partlysunny": "partly-cloudy-night", "nt_mostlycloudy": "overcast-night",
    "nt_fog": "fog-night", "nt_hazy": "haze-night", "nt_chancerain": "partly-cloudy-night-rain",
    "nt_showers": "partly-cloudy-night-drizzle", "nt_chancetstorms": "thunderstorms-night", "nt_tstorms": "thunderstorms-night-rain",
    "nt_chanceflurries": "partly-cloudy-night-snow", "nt_chancesnow": "partly-cloudy-night-snow", "nt_chancesleet": "partly-cloudy-night-sleet",
}

def icon(path, pfx):
    s = open(path, encoding="utf-8").read()
    vb = re.search(r'viewBox="([^"]+)"', s).group(1)
    inner = re.sub(r"(?s)^.*?<svg[^>]*>|</svg>\s*$", "", s)
    inner = re.sub(r'\bid="([^"]+)"', lambda m: 'id="%s%s"' % (pfx, m.group(1)), inner)
    inner = re.sub(r'url\(#([^)]+)\)', lambda m: "url(#%s%s)" % (pfx, m.group(1)), inner)
    inner = re.sub(r'href="#([^"]+)"', lambda m: 'href="#%s%s"' % (pfx, m.group(1)), inner)
    inner = re.sub(r">\s+<", "><", inner).strip()
    return '<svg x="0" y="0" width="60" height="60" viewBox="%s" fill="none">%s</svg>' % (vb, inner)

def chunks(s, n=400):
    out = [s[i:i + n] for i in range(0, len(s), n)]
    return " +\n        ".join("'" + c.replace("\\", "\\\\").replace("'", "\\'") + "'" for c in out)

def lib(name, prov, meth, label, desc, src, pfx):
    body = []
    for k, f in MAP.items():
        body.append("String %s_%s() {\n    return %s\n}\n" % (meth, k, chunks(icon(os.path.join(src, f + ".svg"), "%s%s_" % (pfx, k)))))
    entries = ",\n".join("        '%s': %s_%s()" % (k, meth, k) for k in MAP)
    txt = '''library (
    author: "Rob Cummings",
    category: "Convenience",
    description: "%s",
    documentationLink: "https://github.com/cummingsrob/hubitat-weather-watcher",
    name: "%s",
    namespace: "cummingsrob"
)

/*
 *  Weather Watcher Icons - %s (generated by tools/gen_meteocons.py; do not edit by hand)
 *  Icons: Meteocons by Bas Milius, https://github.com/basmilius/weather-icons, MIT License
 *  (see ICONS-LICENSE.txt). Wrapper code: Apache-2.0, Copyright 2026 Rob Cummings.
 */

/** Icon pack provider (see README). */
Map %s() {
    return [%s: [label: "%s", animated: %s, icons: [
%s
    ]]]
}

%s''' % (desc, name, name, prov, prov.replace("wwIconPacks", "").lower() and {"wwIconPacksMeteocons": "meteocons", "wwIconPacksMeteoconsAnimated": "meteoconsAnimated"}[prov],
         label, "true" if "Animated" in prov else "false", entries, "\n".join(body))
    open(os.path.join(ROOT, "libraries/cummingsrob.%s.groovy" % name), "w", encoding="utf-8").write(txt)

anim, static = sys.argv[1], sys.argv[2]
lib("WeatherWatcherIconsMeteocons", "wwIconPacksMeteocons", "wwMs", "Meteocons (static)", "Meteocons static icon pack for Weather Watcher", static, "mcs")
lib("WeatherWatcherIconsMeteoconsAnimated", "wwIconPacksMeteoconsAnimated", "wwMa", "Meteocons (animated)", "Meteocons animated icon pack for Weather Watcher", anim, "mca")
print("generated Meteocons libraries")
